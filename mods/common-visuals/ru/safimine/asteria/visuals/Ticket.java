package ru.safimine.asteria.visuals;

import java.nio.charset.StandardCharsets;
import java.security.KeyFactory;
import java.security.PublicKey;
import java.security.Signature;
import java.security.spec.X509EncodedKeySpec;
import java.util.Base64;

/**
 * PREMIUM check. The backend signs "v1|name|expiresAtMillis" with its private EC key (P-256, SHA-256);
 * the launcher passes the result as -Dasteria.ticket. Without the private key nobody can make a valid ticket,
 * so copying the jar to another PC or another nick does not unlock the visuals.
 */
public final class Ticket {
    /** public half of backend/data/ticket-private.pem (generated by tools/gen-keys.cjs) */
    static final String PUBLIC_KEY = "MFkwEwYHKoZIzj0CAQYIKoZIzj0DAQcDQgAEIP8HwbgnLDykOdNCLRrtlBFO9h+DHJ5q3YZPKpUpO3R4K7dd3BokNJs1zUAdjX27t5yrPB9bI7AkFJ+ZvPbZ5Q==";

    /** @return expiry time in millis, or -1 if the ticket is missing, forged, for another nick or expired */
    public static long verify(String ticket, String user) {
        try {
            if (ticket == null || user == null) return -1;
            int dot = ticket.indexOf('.');
            if (dot < 0) return -1;
            byte[] payload = Base64.getUrlDecoder().decode(ticket.substring(0, dot));
            byte[] sig = Base64.getUrlDecoder().decode(ticket.substring(dot + 1));
            PublicKey key = KeyFactory.getInstance("EC").generatePublic(new X509EncodedKeySpec(Base64.getDecoder().decode(PUBLIC_KEY)));
            Signature s = Signature.getInstance("SHA256withECDSA");
            s.initVerify(key);
            s.update(payload);
            if (!s.verify(sig)) return -1;
            String[] p = new String(payload, StandardCharsets.UTF_8).split("\\|");
            if (p.length < 3 || !"v1".equals(p[0]) || !p[1].equalsIgnoreCase(user)) return -1;
            long exp = Long.parseLong(p[2]);
            return exp > System.currentTimeMillis() ? exp : -1;
        } catch (Throwable t) {
            return -1;
        }
    }
}
